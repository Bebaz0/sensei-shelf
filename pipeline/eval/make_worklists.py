"""Owner B. Split labelling work across the team.

Reads `labels/assignments.json` (`{labeller_name: [camera_id, ...]}`) and writes
`labels/<name>.worklist.txt` per labeller in the format `cam filename area_id`,
suitable for `python -m pipeline.eval.label_tool --from <path>`.

Each worklist includes:
  - every area of N frames per assigned camera, stratified over the day
    (always includes the last train frame),
  - every calibration line for assigned cameras.
Duplicates are removed. `label_tool` skips already-labelled areas automatically.
"""
import argparse
import json
from collections import defaultdict
from pathlib import Path

from pipeline.common.config import CALIBRATION, PLANOGRAM, ROOT, RUN_FRAMES
from pipeline.common.planogram import load_planogram

ASSIGNMENTS = ROOT / "labels" / "assignments.json"
FRAMES_PER_CAMERA = 4


def pick_frames(filenames: list[str], n: int) -> list[str]:
    """Return `n` filenames evenly spaced across the sorted list; always includes first and last."""
    sorted_files = sorted(filenames)
    if len(sorted_files) <= n:
        return sorted_files
    step = (len(sorted_files) - 1) / (n - 1)
    idxs = sorted({round(i * step) for i in range(n)})
    i = 0
    while len(idxs) < n and i < len(sorted_files):
        if i not in idxs:
            idxs.append(i)
            idxs = sorted(set(idxs))
        i += 1
    return [sorted_files[i] for i in idxs[:n]]


def parse_calibration(path: Path) -> list[tuple[str, str, str]]:
    out = []
    for line in path.read_text().splitlines():
        line = line.split("#")[0].strip()
        if not line:
            continue
        parts = line.split()
        if len(parts) >= 3:
            out.append((parts[0], parts[1], parts[2]))
    return out


def build_worklist(
    cameras: list[str],
    frames_by_camera: dict[str, list[str]],
    planogram: dict,
    calibration: list[tuple[str, str, str]],
    frames_per_camera: int = FRAMES_PER_CAMERA,
) -> list[tuple[str, str, str]]:
    items: list[tuple[str, str, str]] = []
    seen: set[tuple[str, str, str]] = set()
    for cam in cameras:
        area_ids = [a["area_id"] for a in planogram.get(cam, [])]
        for filename in pick_frames(frames_by_camera.get(cam, []), frames_per_camera):
            for area_id in area_ids:
                key = (cam, filename, area_id)
                if key not in seen:
                    seen.add(key)
                    items.append(key)
    assigned = set(cameras)
    for key in calibration:
        if key[0] in assigned and key not in seen:
            seen.add(key)
            items.append(key)
    return items


def write_worklist(path: Path, items: list[tuple[str, str, str]]) -> None:
    lines = ["# Auto-generated by pipeline.eval.make_worklists; rerun to regenerate."]
    for cam, filename, area_id in items:
        lines.append(f"{cam} {filename} {area_id}")
    path.write_text("\n".join(lines) + "\n")


def run(
    assignments_path: Path,
    run_frames_path: Path,
    planogram_path: Path,
    calibration_path: Path,
    out_dir: Path,
    frames_per_camera: int,
) -> None:
    assignments = json.loads(assignments_path.read_text())
    planogram = load_planogram(planogram_path)
    frames_by_camera: dict[str, list[str]] = defaultdict(list)
    for cam, filename in json.loads(run_frames_path.read_text()):
        frames_by_camera[cam].append(filename)
    calibration = parse_calibration(calibration_path) if calibration_path.exists() else []

    out_dir.mkdir(parents=True, exist_ok=True)
    for name, cams in assignments.items():
        items = build_worklist(cams, frames_by_camera, planogram, calibration, frames_per_camera)
        path = out_dir / f"{name}.worklist.txt"
        write_worklist(path, items)
        print(f"{name:16} {len(cams):2} cams  {len(items):4} areas  -> {path.relative_to(ROOT)}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--assignments", type=Path, default=ASSIGNMENTS)
    ap.add_argument("--run-frames", type=Path, default=RUN_FRAMES)
    ap.add_argument("--planogram", type=Path, default=PLANOGRAM)
    ap.add_argument("--calibration", type=Path, default=CALIBRATION)
    ap.add_argument("--out-dir", type=Path, default=ROOT / "labels")
    ap.add_argument("--frames-per-camera", type=int, default=FRAMES_PER_CAMERA)
    args = ap.parse_args()
    run(
        args.assignments, args.run_frames, args.planogram,
        args.calibration, args.out_dir, args.frames_per_camera,
    )
